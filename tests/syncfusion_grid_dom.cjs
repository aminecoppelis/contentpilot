const fs=require('fs');
const path=require('path');
const assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('../.cache/grid-tests/node_modules/jsdom');
const root=process.cwd();
const rows=Array.from({length:24},(_,i)=>`<tr id="request-row-${i}" data-record="${i}"><td>Post ${i}</td><td>${i%3===0?'Scheduled':'Published'}</td><td>${i}</td><td><button data-action="${i}">Open</button></td></tr>`).join('');
const vc=new VirtualConsole();vc.on('jsdomError',e=>console.log('DOM: '+e.message+' '+String(e.detail&&e.detail.stack||'').slice(0,800)));vc.on('log',(...args)=>console.log(...args));
const dom=new JSDOM(`<html class="pg-grid-loading"><head><style>span,div{font-family:Inter!important}.e-icons{font-family:e-icons}</style><style>${fs.readFileSync(path.join(root,'static/css/syncfusion-grid.css'),'utf8')}</style></head><body class="has-sidebar"><div class="tableWrap"><div class="pgGridLoading">Loading</div><table data-syncfusion="true"><thead><tr><th>Post</th><th>Status</th><th>Count</th><th>Actions</th></tr></thead><tbody id="postRequestRows">${rows}</tbody></table></div><nav data-server-pagination></nav><span class="e-icons" id="icon"></span></body></html>`,{url:'http://localhost/',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole:vc});
const win=dom.window;
const originalStyle=win.getComputedStyle.bind(win);
assert.equal(originalStyle(win.document.querySelector('table')).display,'none','Classic table hidden before engine loads');
assert.equal(originalStyle(win.document.querySelector('.pgGridLoading')).display,'flex','Loading state shown from first paint');
win.getComputedStyle=(element)=>originalStyle(element);
win.matchMedia=()=>({matches:false,addListener(){},removeListener(){},addEventListener(){},removeEventListener(){}});
win.ResizeObserver=class{observe(){}unobserve(){}disconnect(){}};
win.HTMLElement.prototype.getBoundingClientRect=function(){return {x:0,y:0,top:0,left:0,right:180,bottom:40,width:180,height:40,toJSON(){return {};}};};
win.HTMLCanvasElement.prototype.getContext=()=>({measureText:(s)=>({width:String(s).length*8})});
win.fetch=async()=>({ok:true,json:async()=>JSON.parse(fs.readFileSync(path.join(root,'static/vendor/syncfusion/locales/fr.json'),'utf8'))});
win.__PG_SYNCFUSION={version:'35.1.37'};win.__LOCALE='fr';win.__DIR='ltr';win.t=(key)=>key==='js.grid.reset'?'Reset':key;
let clicks=0;
win.document.querySelectorAll('[data-action]').forEach(button=>button.addEventListener('click',()=>clicks++));
win.eval(fs.readFileSync(path.join(root,'.cache/grid-tests/ej2.min.js'),'utf8'));
if(process.env.TEST_LICENSE)win.ej.base.registerLicense(process.env.TEST_LICENSE);
win.eval(fs.readFileSync(path.join(root,'static/js/syncfusion-grid.js'),'utf8'));
const pause=()=>new Promise(resolve=>setTimeout(resolve,200));
(async()=>{
  await pause();await pause();
  const element=win.document.querySelector('.pgSyncfusionGrid');
  assert(element,'Grid container created');
  const grid=element.ej2_instances[0];
  assert(grid,'Real Syncfusion instance created');
  assert(!win.document.documentElement.classList.contains('pg-grid-loading'),'Loading state removed after initialization');
  assert.equal(originalStyle(win.document.querySelector('.pgGridLoading')).display,'none');
  assert.equal(grid.dataSource.length,24);
  assert(win.document.getElementById('pg-grid-0_searchbar'),'Search toolbar present');
  assert.equal(grid.getCurrentViewRecords().length,10);
  assert.equal(grid.dataSource[0].c2,0);
  assert.equal(grid.dataSource[0].__cells,undefined,'DOM nodes kept outside grid data');
  assert(win.document.querySelector('[data-server-pagination]').hidden);
  assert.equal(win.document.getElementById('postRequestRows'),null,'Original table detached');
  const firstButton=win.document.querySelector('[data-action="0"]');
  if(!firstButton)throw new Error('Missing action: '+(element.querySelector('.e-content')||element).innerHTML.slice(0,2400)+' cells: '+Array.from(element.querySelectorAll('.e-rowcell')).slice(0,4).map(c=>c.innerHTML).join(' | ')+' keys='+JSON.stringify(grid.getCurrentViewRecords()[0]));
  firstButton.click();assert.equal(clicks,1,'Existing listeners preserved');
  grid.filterByColumn('c1','equal','Scheduled');await pause();
  assert.equal(grid.getCurrentViewRecords().length,8,'Filter sees the full dataset');
  grid.clearFiltering();grid.search('Post 23');await pause();
  assert.equal(grid.getCurrentViewRecords().length,1,'Search spans the full dataset');
  grid.search('');grid.sortColumn('c2','Descending');await pause();
  assert.equal(grid.getCurrentViewRecords()[0].c2,23,'Numeric sorting works');
  grid.clearSorting();grid.goToPage(3);await pause();
  assert.equal(grid.getCurrentViewRecords().length,4,'Grid pagination works');
  grid.goToPage(1);await pause();
  const row=win.document.getElementById('request-row-0');
  assert(row,'Original row IDs preserved');
  assert(win.pgRemoveGridRow(row),'Existing delete action updates grid');await pause();
  assert.equal(grid.dataSource.length,23);
  grid.sortColumn('c2','Ascending');await pause();
  assert.equal(grid.getCurrentViewRecords()[0].c2,1,'Deleted row does not reappear on sorting');
  assert(originalStyle(win.document.getElementById('icon')).fontFamily.includes('e-icons'),'Icon font wins over Inter');
  console.log('PASS: real Syncfusion paging, full-dataset filter, numeric sorting, action listeners, deletion and icon font');
  grid.destroy();win.close();
})().catch(error=>{console.error(error.name+': '+error.message);win.close();process.exitCode=1;});
